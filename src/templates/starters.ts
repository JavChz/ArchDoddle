export function buildDocumentFromTemplate(templateId: string): ProjectDocument | null {
  const tpl = STARTER_TEMPLATES.find((t) => t.id === templateId);
  if (!tpl) return null;
  const now = new Date().toISOString();
  return {
    format: 'archdoddle',
    version: 1,
    id: crypto.randomUUID(),
    name: tpl.name,
    createdAt: now,
    updatedAt: now,
    themeId: tpl.defaultTheme,
    settings: {
      gridStyle: 'dots',
      snapToGrid: true,
      gridSize: 20,
      showNotes: true,
      showSlideFrame: false,
    },
    elements: tpl.createElements(),
  };
}
